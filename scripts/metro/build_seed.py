"""Validate a metro file and print its seed migration.

Usage: python scripts/metro/build_seed.py docs/metro-data/kolkata.json > V6263__metro_kolkata.sql

A broken file prints what is wrong and exits with status 1, and no SQL.
"""
import json, math, sys
from pathlib import Path

MAX_KM_FROM_CENTRE = 60


def km(a_lat, a_lng, b_lat, b_lng):
    p = math.pi / 180
    h = math.sin((b_lat - a_lat) * p / 2) ** 2 + math.cos(a_lat * p) * math.cos(b_lat * p) * math.sin((b_lng - a_lng) * p / 2) ** 2
    return 2 * 6371 * math.asin(math.sqrt(h))


def problems_in(doc):
    problems = []
    seen = {}
    lines_of = {}
    for line in doc["lines"]:
        if len(line["stations"]) < 2:
            problems.append(f"{line['code']} has fewer than 2 stations")
        on_this_line = set()
        for station in line["stations"]:
            code = station["code"]
            if code in on_this_line:
                problems.append(f"{code} appears twice on {line['code']}")
            on_this_line.add(code)
            lines_of.setdefault(code, []).append(line["code"])
            if station.get("latitude") is None or station.get("longitude") is None:
                problems.append(f"{code} has no coordinates")
            elif km(doc["centreLatitude"], doc["centreLongitude"], station["latitude"], station["longitude"]) > MAX_KM_FROM_CENTRE:
                problems.append(f"{code} is more than {MAX_KM_FROM_CENTRE} km from the centre")
            first = seen.setdefault(code, station)
            if first["name"] != station["name"]:
                problems.append(f"{code} has two names: {first['name']} and {station['name']}")
            if (first.get("latitude"), first.get("longitude")) != (station.get("latitude"), station.get("longitude")):
                problems.append(f"{code} has two positions")

    # The interchange list is written by hand, so it has to agree with the lines.
    listed = {i["station"]: sorted(i["lines"]) for i in doc.get("interchanges", [])}
    actual = {code: sorted(lines) for code, lines in lines_of.items() if len(lines) > 1}
    for code in sorted(set(listed) | set(actual)):
        if listed.get(code) != actual.get(code):
            problems.append(f"interchange {code}: listed on {listed.get(code)}, the lines say {actual.get(code)}")
    return problems


def text(value):
    return "'" + value.replace("'", "''") + "'"


def seed_sql(doc):
    out = [f"-- Generated by scripts/metro/build_seed.py from docs/metro-data/{doc['code']}.json. Do not edit by hand.", ""]
    out.append("INSERT INTO discovery.metro_systems (code, name, centre_latitude, centre_longitude) VALUES")
    out.append(f"    ({text(doc['code'])}, {text(doc['name'])}, {doc['centreLatitude']}, {doc['centreLongitude']});")
    out += ["", "INSERT INTO discovery.metro_lines (code, system_code, name, colour, display_order) VALUES"]
    out.append(",\n".join(f"    ({text(l['code'])}, {text(doc['code'])}, {text(l['name'])}, {text(l['colour'])}, {i})" for i, l in enumerate(doc["lines"], 1)) + ";")
    stations = {}
    for line in doc["lines"]:
        for station in line["stations"]:
            stations.setdefault(station["code"], station)
    out += ["", "INSERT INTO discovery.metro_stations (code, system_code, name, latitude, longitude) VALUES"]
    out.append(",\n".join(f"    ({text(c)}, {text(doc['code'])}, {text(s['name'])}, {s['latitude']}, {s['longitude']})" for c, s in stations.items()) + ";")
    rows = [f"    ({text(l['code'])}, {p}, {text(s['code'])})" for l in doc["lines"] for p, s in enumerate(l["stations"], 1)]
    out += ["", "INSERT INTO discovery.metro_line_stations (line_code, position, station_code) VALUES"]
    out.append(",\n".join(rows) + ";")
    return "\n".join(out) + "\n"


def main():
    doc = json.loads(Path(sys.argv[1]).read_text(encoding="utf8"))
    problems = problems_in(doc)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        raise SystemExit(1)
    sys.stdout.reconfigure(newline="\n")
    sys.stdout.write(seed_sql(doc))


if __name__ == "__main__":
    main()
